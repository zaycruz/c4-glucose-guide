"""Regenerate CONTRACT.md from live responses. Usage: python3 -I scripts/contract.py [baseUrl]"""
import json
import sys
import urllib.request

BASE = (sys.argv[1] if len(sys.argv) > 1 else "https://c4-glucose-guide.zay-259.workers.dev").rstrip("/")
DEMO = "c4-N0632"


def get(path):
    req = urllib.request.Request(BASE + path, headers={"user-agent": "c4-contract-gen/1.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


roster, det, coh = get("/api/c4/survivors"), get(f"/api/c4/survivors/{DEMO}"), get("/api/c4/cohort")
adv = get(f"/api/c4/survivors/{DEMO}/advice")
j = lambda o: json.dumps(o, indent=2, ensure_ascii=False)
trim = lambda v, k=4: v[:k] + ["…"] if isinstance(v, list) and len(v) > k else v

d2 = dict(det)
keep = ("walk_effect_own", "cohort_walk_dinner", "cohort_late", "trial_fast_hba1c_group", "real_late_dinner")
d2["evidence"] = det["evidence"][:3] + [e for e in det["evidence"] if e["id"] in keep]
ch = det["charts"]
d2["charts"] = {
    "dailyProfile": {"hours": trim(ch["dailyProfile"]["hours"]), "series": [{"label": s["label"], "values": trim(s["values"])} for s in ch["dailyProfile"]["series"]],
                     "unit": ch["dailyProfile"]["unit"], "targetRange": ch["dailyProfile"]["targetRange"]},
    "dinnerResponse": {"minutes": trim(ch["dinnerResponse"]["minutes"]), "unit": ch["dinnerResponse"]["unit"],
                       "you": {k: trim(v) for k, v in ch["dinnerResponse"]["you"].items()}, "cohort": {k: trim(v) for k, v in ch["dinnerResponse"]["cohort"].items()}},
    "walkResponse": "same shape as dinnerResponse: you.noWalk, you.walk, you.nNoWalk, you.nWalk, cohort.noWalk, cohort.walk",
    "walkDose": ch["walkDose"],
    "overnightFast": {k: trim(v, 5) for k, v in ch["overnightFast"].items()},
    "checkups": ch["checkups"],
}
cohort_keys = {k: (list(v.keys()) if isinstance(v, dict) else type(v).__name__) for k, v in coh.items()}
coh_example = {
    "effects.walkAfterDinner": coh["effects"]["walkAfterDinner"], "effects.lateDinner": coh["effects"]["lateDinner"],
    "walkDose[1]": coh["walkDose"][1],
    "trial.fastVsCoachingBySubgroup.hba1c_pct['blood sugar: type 2 diabetes']": coh["trial"]["fastVsCoachingBySubgroup"]["hba1c_pct"]["blood sugar: type 2 diabetes"],
    "trial.adherence['coaching + overnight fast']": coh["trial"]["adherence"]["coaching + overnight fast"],
    "realWorld.cgmacros.lateDinner": coh["realWorld"]["cgmacros"]["lateDinner"],
}

md = f"""# C4 Glucose Guide: API contract

Base URL (deployed): `{BASE}`
All `/api/c4/*` responses are JSON with `access-control-allow-origin: *`, cached 60 s. The examples below are real responses from that deployment, generated by `scripts/contract.py`; long arrays are trimmed with `"…"`.
The survivors are synthetic (Crane Lab hackathon set). Nobody in them is real.

## Survivor ids and status

- `survivorId` = `c4-<participant_id>`, e.g. `{DEMO}`. Unknown ids return 404 `{{"error":"unknown survivorId","survivorId":"…"}}`.
- `status` is `"ok" | "watch" | "alert"`. It comes from fixed CGM thresholds (international consensus targets) applied to the latest sensor window (weeks 11-12, else weeks 1-2):
  - **alert**: time in range 70-180 below 70%, or more than 5% of readings above 250, or more than 4% below 70.
  - **watch**: time in range below 90%, or more than 5% above 180, or average sugar up 10+ mg/dL since weeks 1-2.
  - **ok**: everything else.
- The roster is sorted alert → watch → ok, then by id.

## `GET /api/c4/survivors`

Roster tiles: {len(roster)} survivors, sorted alert → watch → ok. Each tile also carries `tags[]` (see the detail fields below) so a coach can scan the signal without opening the panel. These are the sensor wearers in the dataset's 100-person app sample.

```json
{j(roster[:2])}
```

## `GET /api/c4/survivors/:id`

| field | type | notes |
|---|---|---|
| `survivorId`, `displayName`, `status`, `headline`, `summary`, `updatedAt` | string | `updatedAt` is the time of the last sensor reading |
| `statusReasons` | string[] | why the status was set |
| `tags[]` | `{{label, tone, evidenceId}}` | up to 4 short signals, same as on the roster tile. `tone`: `risk`, `warn`, `good`, `info`. Each number in `label` is the value or n of the evidence item `evidenceId` (checked by `scripts/e2e.mjs`). |
| `profile` | object | age, sex, cancerType, yearsSinceTreatment, bloodSugarGroup, group (trial arm), workSchedule |
| `evidence[]` | `{{id, label, value, unit, ci: [lo, hi] \\| null, n, scope, method, caveat}}` | `scope`: `person` (their data), `cohort` (program within-person estimate), `trial` (randomized arms), `real` (CGMacros real-data check), `rule` (thresholds) |
| `recommendations[]` | `{{id, title, text, basis, evidenceIds[]}}` | `basis`: `personal`, `cohort`, `trial`, `rule`. Every measured number in `text` is a value, CI bound or n of a listed evidence item. The rest are fixed wording (8 pm, 13 hours, 70-180, 95% CI, …). `scripts/e2e.mjs` enforces this. |
| `charts` | object of plain arrays | see below |
| `dataNote` | string | notice that the data is synthetic |

Charts:
- `dailyProfile`: `hours[24]`; `series[{{label, values[24]}}]` holds the mean mg/dL for each hour of the day, for weeks 1-2 and weeks 11-12; `targetRange` is `[70,180]`.
- `dinnerResponse`: `minutes` = `[0,15,…,180]`. `you.early[]` and `you.late[]` hold the mean mg/dL above the pre-meal reading (`null` when there are no such dinners), with counts in `you.nEarly` and `you.nLate`. `cohort.early[]` and `cohort.late[]` give the same curves for the cohort.
- `walkResponse`: `minutes`; `you.noWalk[]`, `you.walk[]`, `you.nNoWalk`, `you.nWalk`; `cohort.noWalk[]`, `cohort.walk[]`.
- `walkDose` (cohort): `bins[]`, `est[]`, `lo[]`, `hi[]`, `nMeals[]`. Each entry is the rise compared with no walk, for the same person, by walk length.
- `overnightFast`: `hours[]` and `morningGlucose[]`, paired per night (for a scatter plot).
- `checkups`: `metrics[]`, `week0[]`, `week12[]` (`null` for people who left early).

Example (`{DEMO}`, trimmed):

```json
{j(d2)}
```

## `GET /api/c4/survivors/:id/advice`

Optional. Workers AI (`{adv['model']}`) rewrites the recommendations in plain language; a call takes about 3-8 s. Each rewrite is checked, and the Worker drops it and returns the template (`source: "template"`, with a `rejected` object) when it:
- uses a number that is not in the template or its evidence (`rejected.untracedNumbers`);
- adds a causal verb such as helped, caused, lowered or reduced that the template does not use (`rejected.addedCausalWords`).

```json
{j(adv)}
```

## `GET /api/c4/cohort`

Cohort findings for a program-level view. Top-level keys:

```json
{j(cohort_keys)}
```

- `effects.<name>` = `{{est, lo, hi, people, rows}}`: within-person estimates (person fixed effects) with cluster-bootstrap 95% CIs. Names: `walk`, `walkAfterDinner`, `walkAfterOtherMeals`, `lateDinner`, `carbsPer10g`, `fastMorningPerHour`, `fast13Morning`, plus iAUC versions.
- `walkDose[]`, `dinnerHour[]`: `{{bin, est, lo, hi, n_meals}}`, for the dose-response charts.
- `trial.contrasts.<outcome>["A vs B"]`: randomized difference in the week 12 minus week 0 change. `trial.fastVsCoachingBySubgroup`: the same difference by starting blood sugar group and by night shift. `trial.adherence`: what each arm actually did.
- `realWorld.cgmacros`, `realWorld.nhanesSurvivors`: the same questions answered from real data.

```json
{j(coh_example)}
```

## `GET /`

Standalone demo page (`public/index.html`). It shows the roster, the survivor panel with charts and evidence, and a **Cohort findings** tab (`/#cohort`).
"""
open("CONTRACT.md", "w").write(md)
print("CONTRACT.md written,", len(md.splitlines()), "lines")
